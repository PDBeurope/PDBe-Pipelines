"""Helper classes with variety of functions
"""

import argparse
from gemmi import cif
import gemmi



# region mmcif manipulation
def fix_assembly_file(assembly_input: str, assembly_output: str) -> None:
    """Modifies _struct_conn and _pdbx_nonpoly_scheme categories so that
    they match the actual atom_site generated by Model-server.

    Note: Model-server modifies chain information based on the
        symmetry used and that confuses all the software which uses these
        fields.

    Args:
        assembly_input: Path to the input assembly cif file
        assembly_output: Path to output assembly cif file
    """

    doc_assembly = cif.read(assembly_input)
    cif_block_assembly = doc_assembly.sole_block()
    
    chains = set(
        cif_block_assembly.get_mmcif_category("_atom_site.")["auth_asym_id"]
    )
    # all the chains we have, e.g. A, B, D, D-2, D-3, etc.
    operator_list = [""] + list(
        {i[i.index("_") :] for i in chains if "_" in i}
    )  # unique operators, e.g. [-2,-3] + identity

    _fix_struct_conn(cif_block_assembly, chains, operator_list)
    _fix_nonpoly_scheme(cif_block_assembly, chains, operator_list)
    _fix_branch_scheme(cif_block_assembly, chains, operator_list)

    doc_assembly.write_file(assembly_output, cif.Style.Pdbx)


def _filter_mmcif_category(
    cif_block: gemmi.cif.Block, field: str, chains: list[str], keys_to_keep: list[str]
):
    """Filter out the entries in the table corresponding to input field
    which are not part of the molecular assembly.

    Args:
        cif_block: Parsed Block object from gemmi of input structure
        field: The name of field in cif_block to be filtered
        chains: list of chains found in input structure.
        keys_to_keep: list of category fields which should
            be unique.
    """
    mmcif = cif_block.get_mmcif_category(field)
    indices = []
    for i in keys_to_keep:
        indices += [index for index, item in enumerate(mmcif[i]) if item in chains]

    indices_to_keep = sorted(set(indices))

    for k in mmcif:
        mmcif[k] = [mmcif[k][i] for i in indices_to_keep]

    cif_block.set_mmcif_category(field, mmcif, raw=False)


def _modify_mmcif_chains(
    cif_block: gemmi.cif.Block,
    field: str,
    operator_list: list[str],
    fields_to_modify: list[str],
) -> None:
    """Expand the table corresponding to input field with given symmetry operators.

    Args:
        cif_block: Parsed Block object from gemmi of input structure
        field: Field to be modified
        operator_list: list of operators used by model-server
        fields_to_modify: list of category names which
            should be modified
    """
    mmcif = cif_block.get_mmcif_category(field)

    keys = list(mmcif.keys())
    new_mmcif = {i: [] for i in keys}

    keys = [k for k in keys if k not in fields_to_modify]

    for i in range(0, len(mmcif[keys[0]])):
        for operator in operator_list:
            for f in fields_to_modify:
                value = mmcif[f][i]
                if isinstance(value, str):
                    value = value.strip('"')
                new_mmcif[f].append(value + operator)  # modify some columns

            for k in keys:
                value = mmcif[k][i]
                if isinstance(value, str):
                    value = value.strip('"')
                new_mmcif[k].append(value)  # keep the remaining columns itact

    cif_block.set_mmcif_category(field, new_mmcif, raw=False)


def _fix_struct_conn(
    cif_block: gemmi.cif.Block, chains: list[str], operator_list: list[str]
) -> None:
    """Modify auth_asym_id and label_asym_information in
    _struct_conn table, so that bonds connectivity is correctly picked
    both by arpeggio and chimerax.

    Args:
        cif_block: Parsed Block object from gemmi of input structure.
        chains: list of all chains found in the input structure.
        operator_list: list of all operators symmetry
            operators including identity. (e.g. ['', '-2', '-3'])
    """
    if "_struct_conn." not in cif_block.get_mmcif_category_names():
        return
    fields_to_modify = [
        "ptnr1_auth_asym_id",
        "ptnr2_auth_asym_id",
        "ptnr1_label_asym_id",
        "ptnr2_label_asym_id",
    ]

    _modify_mmcif_chains(cif_block, "_struct_conn.", operator_list, fields_to_modify)

    struct_conn = cif_block.get_mmcif_category("_struct_conn.")

    struct_conn["id"] = [
        f"bond{i+1}" for i in range(0, len(struct_conn["id"]))
    ]  # add new ids to the individual bonds

    cif_block.set_mmcif_category("_struct_conn.", struct_conn, raw=False)

    _filter_mmcif_category(cif_block, "_struct_conn.", chains, fields_to_modify[0:2])


def _fix_nonpoly_scheme(
    cif_block: gemmi.cif.Block, chains: list[str], operator_list: list[str]
) -> None:
    """Modify asym_id and pdb_strand_id information in _pdbx_nonpoly_scheme
    table, so ligands are correctly picked both by arpeggio and chimerax.

    Args:
        cif_block: Parsed Block object from gemmi of input structure
        chains: list of all chains found in the input structure.
        operator_list: list of all operators symmetry
            operators including identity. (e.g. ['', '-2', '-3'])
    """
    if "_pdbx_nonpoly_scheme." not in cif_block.get_mmcif_category_names():
        return
    fields_to_modify = ["asym_id", "pdb_strand_id"]

    _modify_mmcif_chains(
        cif_block, "_pdbx_nonpoly_scheme.", operator_list, fields_to_modify
    )

    _filter_mmcif_category(
        cif_block, "_pdbx_nonpoly_scheme.", chains, ["pdb_strand_id"]
    )


def _fix_branch_scheme(
    cif_block: gemmi.cif.Block, chains: list[str], operator_list: list[str]
) -> None:
    """Modify asym_id and pdb_strand_id information in _pdbx_nonpoly_scheme
    table, so ligands are correctly picked both by arpeggio and chimerax.

    Args:
        cif_block: Parsed Block object from gemmi of input structure
        chains: list of all chains found in the input structure
        operator_list: list of all operators symmetry
            operators including identity. (e.g. ['', '-2', '-3'])
    """
    if "_pdbx_branch_scheme." not in cif_block.get_mmcif_category_names():
        return
    fields_to_modify = [
        "asym_id",  # nonpoly asymid-> structasymid
        "pdb_asym_id",
    ]  # nonpoly pdbstrandid -> authasymid

    _modify_mmcif_chains(
        cif_block, "_pdbx_branch_scheme.", operator_list, fields_to_modify
    )

    _filter_mmcif_category(cif_block, "_pdbx_branch_scheme.", chains, ["pdb_asym_id"])


def check_branched_entities(assembly_path: str) -> bool:
    """Compare entity_ids in branch_scheme and entity_branch_link.
    If not all entities in _pdbx_branch_scheme are present in _pdbx_entity_branch_link,
    the assembly will not contain the correct branch components in _atom_site.

    Args:
        assembly_path: Path to the assembly cif file

    Returns:
        True if all entity_id in _pdbx_entity_branch_link are present in '_entity'
        else False
    """

    doc = cif.read(assembly_path)
    cif_block_assembly = doc.sole_block()

    if (
        "_pdbx_branch_scheme." not in cif_block_assembly.get_mmcif_category_names()
    ):  # Does not contain branched entities
        return True

    a = set(
        cif_block_assembly.get_mmcif_category("_pdbx_entity_branch_link.")["entity_id"]
    )
    b = set(cif_block_assembly.get_mmcif_category("_entity.")["id"])

    if a - b:
        return False
    return True


def check_nonpoly_entities(assembly_path: str) -> bool:
    """Compare entity_ids in nonpoly_scheme and _entity.
    If not all entities in nonpoly_scheme are present in _entity,
    the assembly will not contain the correct chemical components in _atom_site.

    Args:
        assembly_path: Path to the assembly cif file

    Returns:
        True if all entity_id in _pdbx_nonpoly_scheme are present in '_entity'
        else False
    """

    doc = cif.read(assembly_path)
    cif_block_assembly = doc.sole_block()

    if (
        "_pdbx_nonpoly_scheme." not in cif_block_assembly.get_mmcif_category_names()
    ):  # Does not contain branched entities
        return True

    a = set(cif_block_assembly.get_mmcif_category("_pdbx_nonpoly_scheme.")["entity_id"])
    b = set(cif_block_assembly.get_mmcif_category("_entity.")["id"])

    if a - b:
        return False
    return True


def get_orig_auth_and_operator(
    contacts: dict[str, dict[str, str]]
) -> dict[str, dict[str, str]]:
    """Adds orig_auth_asym_id and operator fields to contacts

    Args:
        contacts: A dictionary containing intreactions information from arpeggio

    Returns:
        A dictionary of contacts from arpeggio after adding orig_auth_asym_id and
        operator fields
    """

    if "_" in contacts["bgn"]["auth_asym_id"]:
        contacts["bgn"]["orig_auth_asym_id"] = contacts["bgn"]["auth_asym_id"].split(
            "_"
        )[0]
        contacts["bgn"]["operator"] = (
            "_" + contacts["bgn"]["auth_asym_id"].split("_")[1]
        )
    else:
        contacts["bgn"]["orig_auth_asym_id"] = contacts["bgn"]["auth_asym_id"]
        contacts["bgn"]["operator"] = ""

    if "_" in contacts["end"]["auth_asym_id"]:
        contacts["end"]["orig_auth_asym_id"] = contacts["end"]["auth_asym_id"].split(
            "_"
        )[0]
        contacts["end"]["operator"] = (
            "_" + contacts["end"]["auth_asym_id"].split("_")[1]
        )
    else:
        contacts["end"]["orig_auth_asym_id"] = contacts["end"]["auth_asym_id"]
        contacts["end"]["operator"] = ""
    return contacts


def create_parser():
    
    parser = argparse.ArgumentParser(
        description="Fix assembly mmCIF file by correcting chain ids."
    )

    parser.add_argument(
        "--input_file",
        help="Path to assembly mmCIF file generated by model-server"
    )

    parser.add_argument(
        "--output_file",
        help="Path to fixed assembly mmCIF file"
    )


def main():
    
    parser = create_parser()
    args = parser.parse_args()

    fix_assembly_file(args.input_file, args.output_file)


if __name__ == '__main__':
    main()