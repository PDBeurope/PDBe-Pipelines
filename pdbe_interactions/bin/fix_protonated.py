#!/usr/bin/env python
import os
import argparse
from gemmi import cif


def fix_chimerax_file(
    assembly: str, 
    protonated_input: str, 
    protonated_fixed: str) -> None:
    """Copies '_pdbx_nonpoly_scheme' from assembly file
     to protonated structure If '_pdbx_nonpoly_scheme' is not present in
     protonated strructure.

    Note: As of ChimeraX 0.9 (2019-02-21), '_pdbx_nonpoly_scheme' is not copied by ChimeraX.

    Args:
        assembly: Path to fixed assembly file generated by model-server.
        protonated_input: Path to the protonated file by ChimeraX.
        protonated_fixed: Path to the fixed protonated file
    """
    doc_assembly = cif.read(assembly)
    cif_block_assembly = doc_assembly.sole_block()

    doc_protonated = cif.read(protonated_input)
    cif_block_protonated = doc_protonated.sole_block()

    if (
        "_pdbx_nonpoly_scheme." not in cif_block_assembly.get_mmcif_category_names()
        and "_pdbx_nonpoly_scheme."
        not in cif_block_protonated.get_mmcif_category_names()
    ):
        return

    if "_pdbx_nonpoly_scheme." not in cif_block_protonated.get_mmcif_category_names():
        cif_block_protonated.set_mmcif_category(
            "_pdbx_nonpoly_scheme.",
            cif_block_assembly.get_mmcif_category("_pdbx_nonpoly_scheme."),
            raw=True,
        )

    # Add suffix _h to mmcif file header
    protonated_cif = doc_protonated.as_string(cif.Style.Pdbx)
    filename = os.path.basename(protonated_fixed)
    updated_protonated_cif = protonated_cif.replace(
        protonated_cif.split("\n")[0], f"data_{filename}"
    )
    with open(protonated_fixed, "w") as fh:
        fh.write(updated_protonated_cif)


def create_parser():
    
    parser = argparse.ArgumentParser(
        description="Fix protonated cif by adding missing fields."
    )

    parser.add_argument(
        "--assembly_file",
        help="Path to fixed assembly mmCIF file"
    )

    parser.add_argument(
        "--input_protonated",
        help="Path to input protonated cif"
    )

    parser.add_argument(
        "--output_protonated",
        help="Path to fixed protonated cif"
    )

    return parser

def main():
    
    parser = create_parser()
    args = parser.parse_args()

    fix_chimerax_file(args.assembly_file, args.input_protonated, args.output_protonated)


if __name__ == '__main__':
    main()